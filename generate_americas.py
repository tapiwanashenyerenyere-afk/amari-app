"""
Generate SVG paths for North America, Central America, and South America.
Run: python generate_americas.py
Output: americas_paths.html (visual test) + prints d="" values to console
"""

def lon_to_x(lon):
    """Map longitude -170..-30 to x 0..450"""
    return (lon - (-170)) / ((-30) - (-170)) * 450

def lat_to_y(lat):
    """Map latitude -58..72 to y 650..0 (SVG y is inverted)"""
    return 650 - (lat - (-58)) / (72 - (-58)) * 650

def coords_to_path(coords, close=True):
    parts = []
    for i, (lat, lon) in enumerate(coords):
        x = round(lon_to_x(lon), 1)
        y = round(lat_to_y(lat), 1)
        if i == 0:
            parts.append(f"M{x},{y}")
        else:
            parts.append(f"L{x},{y}")
    if close:
        parts.append("Z")
    return " ".join(parts)

