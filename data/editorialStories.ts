export const EDITORIAL_CATEGORIES = ['All', 'Policy', 'Culture', 'Film', 'Business'] as const;

export function getEditorialStories() {
  return [...EDITORIAL_STORIES].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime(),
  );
}

export function getEditorialStory(idOrSlug: string) {
  return EDITORIAL_STORIES.find(
    (story) => story.id === idOrSlug || story.slug === idOrSlug,
  ) ?? null;
}

export function getFeaturedEditorialStory() {
  return [...EDITORIAL_STORIES]
    .filter((story) => story.featured && story.image)
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())[0] ?? null;
}

export function getEditorialArchive(limit?: number, excludeId?: string) {
  const stories = getEditorialStories().filter((story) => story.id !== excludeId);
  return typeof limit === 'number' ? stories.slice(0, limit) : stories;
}
